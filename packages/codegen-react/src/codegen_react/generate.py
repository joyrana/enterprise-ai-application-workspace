GENERATOR = "codegen-react"
GENERATOR_VERSION = "0.6.0"
MANIFEST = "workspace-manifest.json"


class GenerationBlocked(Exception):
    """The UI IR has errors; code is not generated until they are fixed."""

    def __init__(self, issues: list[UiIssue]) -> None:
        super().__init__(f"{len(issues)} UI error(s) block code generation")
        self.issues = issues


class GeneratedProject(BaseModel):
    generator: str
    spec_revision: int | None
    design_system: str
    files: dict[str, str] = Field(description="Path -> content, in a stable order.")
    warnings: list[UiIssue] = Field(default_factory=list)

    def sha256(self, path: str) -> str:
        return hashlib.sha256(self.files[path].encode("utf-8")).hexdigest()


def toolchain() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(
        resources.files(__package__).joinpath("toolchain.json").read_text(encoding="utf-8")
    )
    return data


def pascal(identifier: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^a-zA-Z0-9]+", identifier) if part)


def package_name(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:60].strip("-")
    return f"{slug}-app" if slug and slug[0].isalpha() else "generated-app"


def design_system_label(contract: DesignSystemContract, theme: BrandTheme | None) -> str:
    base = f"{contract.id}@{contract.version}"
    return f"{theme.selector} ({base})" if theme is not None else base


def _header(spec_revision: int | None, contract: DesignSystemContract) -> str:
    revision = f"r{spec_revision}" if spec_revision is not None else "an unsaved spec"
    return (
        f"// Generated by {GENERATOR}@{GENERATOR_VERSION} from spec {revision} "
        f"(UI IR v1, design system {contract.id}@{contract.version}).\n"
        "// You may edit this file: upgrading in the workspace merges your edits with the regenerated code.\n"
    )


def _screen_file(screen: RenderedScreen, header: str, contract: DesignSystemContract, bindings: DataBindings) -> str:
    packages = {m.package for m in contract.mappings.values()} - {"html"}
    if len(packages) != 1:
        raise GenerationError("expected exactly one component package in the contract")
    [package] = packages
    printer = Printer(replace(bindings, current_route=screen.route))
    body = printer.nodes(screen.root, 3)
    used = components_in(screen.root) | printer.extra_components
    library = sorted(c for c in used if is_library_component(c))
    has_layout = needs_layout(screen.root)
    lines = [header.rstrip("\n"), ""]
    if library:
        lines.append(f"import {{ {', '.join(library)} }} from {literal(package)};")
    router = sorted(
        name
        for name, used_ in (("useNavigate", printer.uses_navigate), ("useSearchParams", printer.uses_search_params))
        if used_
    )
    if router:
        lines.append(f'import {{ {", ".join(router)} }} from "react-router-dom";')
    if printer.uses_confirm:
        lines.append('import { ConfirmDelete } from "../components/ConfirmDelete";')
    if printer.forms:
        lines.append('import { useFormState } from "../forms";')
    if printer.data_imports:
        lines.append(f'import {{ {", ".join(sorted(printer.data_imports))} }} from "../data/entities";')
    if printer.store_imports:
        lines.append(f'import {{ {", ".join(sorted(printer.store_imports))} }} from "../data/store";')
    if has_layout:
        lines.append('import { useLayoutStyles } from "../layout";')
    lines.append("")
    constants = printer.label_constants()
    if constants:
        lines.extend(constants)
        lines.append("")
    name = f"{pascal(screen.screen_id)}Screen"
    lines.append(f"export function {name}() {{")
    if has_layout:
        lines.append("  const layout = useLayoutStyles();")
    lines.extend(f"  {declaration}" for declaration in printer.declarations())
    lines.append("  return (")
    lines.append("    <>")
    lines.extend(body)
    lines.append("    </>")
    lines.append("  );")
    lines.append("}")
    return "\n".join(lines) + "\n"


_FORMS = """import { useState, type FormEvent } from "react";

/**
 * Form state for a generated form: the browser checks the constraints from the specification
 * (required, min, max, lengths, pattern); invalid fields get their message shown by Fluent Field.
 * Forms bound to an entity pass `save`, which stores the record (see src/data); its errors are shown.
 */
export function useFormState(options: { save?: (data: FormData) => Promise<void> | void } = {}) {
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [submitted, setSubmitted] = useState(false);
  const [saveError, setSaveError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  const onSubmit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const form = event.currentTarget;
    const next: Record<string, string> = {};
    for (const element of Array.from(form.elements)) {
      if (
        (element instanceof HTMLInputElement ||
          element instanceof HTMLSelectElement ||
          element instanceof HTMLTextAreaElement) &&
        element.name &&
        !element.validity.valid
      ) {
        next[element.name] = element.validationMessage;
      }
    }
    setErrors(next);
    setSaveError(null);
    if (Object.keys(next).length > 0) {
      setSubmitted(false);
      return;
    }
    if (options.save) {
      setSaving(true);
      try {
        await options.save(new FormData(form));
      } catch (error) {
        setSaveError(error instanceof Error ? error.message : "Saving failed.");
        setSaving(false);
        return;
      }
      setSaving(false);
    }
    setSubmitted(true);
  };

  return { errors, submitted, saveError, saving, onSubmit };
}
"""

