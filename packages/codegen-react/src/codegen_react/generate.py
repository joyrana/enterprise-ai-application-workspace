"""Generate a complete Vite + React + TypeScript + Fluent 2 project from a spec revision.

Deterministic: the same spec revision, design system and generator version give
byte-identical files (no timestamps, sorted keys, stable ordering), so diffs
between revisions show only real changes. Generation is refused while the UI IR
has errors (ADR-0013); warnings (placeholders) are carried into the output as
visible "not supported yet" markers.
"""

