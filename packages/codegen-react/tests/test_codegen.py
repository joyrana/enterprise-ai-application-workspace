def test_brand_themes_change_the_fluent_theme_only(spec: ApplicationSpec) -> None:
    from design_system import BrandTheme

    default = generate_project(spec, CONTRACT, spec_revision=2)
    assert "export const appTheme: Theme = webLightTheme;" in default.files["src/theme.ts"]
    assert "<FluentProvider theme={appTheme}>" in default.files["src/App.tsx"]
    theme = BrandTheme(
        id="acme", name='Acme "Red"', base="fluent2", brand_color="#8A1538", font_family="Inter, sans-serif"
    )
    branded = generate_project(spec, CONTRACT, spec_revision=2, theme=theme)
    source = branded.files["src/theme.ts"]
    assert '  80: "#8a1538",' in source
    assert source.count(': "#') == 16  # sixteen BrandVariants
    assert '  fontFamilyBase: "Inter, sans-serif",' in source
    assert 'Organization brand theme "Acme \\"Red\\"" ("org-acme") on Fluent 2.' in source
    assert branded.design_system == "org-acme (fluent2@1.0.0)"
    assert json.loads(branded.files[MANIFEST])["design_system"] == "org-acme (fluent2@1.0.0)"
    changed = {p for p in default.files if default.files[p] != branded.files.get(p)}
    assert changed == {"src/theme.ts", MANIFEST}
