def test_diff_between_revisions_shows_only_real_changes(raw: dict[str, Any]) -> None:
    before = generate_project(load_spec(raw), CONTRACT, spec_revision=2)
    raw["entities"][0]["fields"].append({"name": "comment", "type": "text"})
    after = generate_project(load_spec(raw), CONTRACT, spec_revision=3)
    diffs = {d.path: d for d in diff_projects(before, after)}
    screen = diffs["src/screens/AdjustmentRulesScreen.tsx"]
    assert screen.status == "modified"
    added = [
        line[1:].strip() for line in screen.unified.splitlines() if line.startswith("+") and not line.startswith("+++")
    ]
    assert '<TableHeaderCell>{"Comment"}</TableHeaderCell>' in added
    assert screen.additions == 4  # new column header and row cell, plus the revision in the header lines
    assert "package.json" not in diffs
    assert diff_projects(before, before) == []


