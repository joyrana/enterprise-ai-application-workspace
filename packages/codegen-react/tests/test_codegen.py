def test_allowlist_matches_the_workspace_preview() -> None:
    source = (ROOT / "apps" / "workspace-web" / "src" / "design" / "RenderTree.tsx").read_text(encoding="utf-8")
    block = source.split("export const REGISTRY", 1)[1].split("\n};", 1)[0]
    entry = re.compile(r'\n  "?([A-Za-z0-9]+)"?: \{\s*render: [^,]+,\s*props: (TYPOGRAPHY|\{.*?\})\s*,?\s*\}', re.S)
    found: dict[str, set[str]] = {}
    for match in entry.finditer(block):
        props = match.group(2)
        found[match.group(1)] = {"as"} if props == "TYPOGRAPHY" else set(re.findall(r'"?([a-zA-Z][\w-]*)"?:', props))
    assert found == {name: set(props) for name, props in ALLOWED.items()}


