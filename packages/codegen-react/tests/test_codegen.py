def test_printer_refuses_unknown_components_and_props() -> None:
    with pytest.raises(GenerationError, match="component 'script'"):
        print_nodes([RenderNode(component="script", text="x")], 0)
    with pytest.raises(GenerationError, match="prop 'onClick'"):
        print_nodes([RenderNode(component="Button", props={"onClick": "alert(1)"})], 0)
    with pytest.raises(GenerationError, match="invalid value"):
        print_nodes([RenderNode(component="Input", props={"type": "password"})], 0)


