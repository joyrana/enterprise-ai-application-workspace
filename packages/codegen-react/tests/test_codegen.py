def test_hostile_spec_text_stays_inside_string_literals(raw: dict[str, Any]) -> None:
    evil = 'Pwn"}</Title2><script>alert(1)</script>{`${process.env.X}`} */ \u2028 é'
    raw["metadata"]["name"] = evil
    raw["screens"][0]["name"] = evil
    raw["screens"][0]["components"][0]["label"] = evil
    project = generate_project(load_spec(raw), CONTRACT, spec_revision=2)
    for path, content in project.files.items():
        if path.endswith((".tsx", ".ts")):
            # The text appears only as complete, escaped string literals; nothing of it is left as code.
            outside = content.replace(literal(evil), '""')
            assert "<script>" not in outside, path
            assert "process.env" not in outside, path
            assert "\u2028" not in content, path
    screen = project.files["src/screens/AdjustmentRulesScreen.tsx"]
    assert f'<Title2 as={{"h1"}}>{{{literal(evil)}}}</Title2>' in screen
    assert "&lt;script&gt;" in project.files["index.html"]
    assert re.fullmatch(r"pwn-[a-z0-9-]+-app", json.loads(project.files["package.json"])["name"])


