def _routes_ts(header: str, screens: list[tuple[str, str, str]]) -> str:
    lines = [header.rstrip("\n"), "", 'import type { Routes } from "@angular/router";']
    for cls, _, _ in screens:
        lines.append(f"import {{ {cls} }} from {literal('./screens/' + cls_file(cls))};")
    lines += ["", "export const routes: Routes = ["]
    for cls, path, title in screens:
        lines.append(f"  {{ path: {literal(path)}, component: {cls}, title: {literal(title)} }},")
    if screens:
        first = screens[0][1]
        lines.append(f'  {{ path: "", pathMatch: "full", redirectTo: {literal(first)} }},')
        lines.append(f'  {{ path: "**", redirectTo: {literal(first)} }},')
    lines += ["];", ""]
    return "\n".join(lines)


def cls_file(cls: str) -> str:
    """AdjustmentRulesScreen -> adjustment-rules-screen (Angular file naming)."""
    out = []
    for i, ch in enumerate(cls):
        if ch.isupper() and i:
            out.append("-")
        out.append(ch.lower())
    return "".join(out)


