def _list_routes(document: UiDocument) -> dict[str, str]:
    out: dict[str, str] = {}
    for screen in document.screens:
        for node in screen.body:
            if isinstance(node, Table) and node.entity_id and node.entity_id not in out:
                out[node.entity_id] = screen.route
    return out


def generate_project(
    spec: ApplicationSpec,
    contract: DesignSystemContract,
    *,
    spec_revision: int | None = None,
    document: UiDocument | None = None,
    theme: BrandTheme | None = None,
) -> GeneratedProject:
    if contract.framework != "angular":
        raise GenerationError(f"{contract.name} is not an Angular design system")
    document = document or derive_document(spec, spec_revision=spec_revision)
    issues = validate_document(document, spec)
    errors = [i for i in issues if i.severity == "error"]
    if errors:
        raise GenerationBlocked(errors)
    header = _header(spec_revision, contract)
    title = spec.metadata.name
    routes = {s.id: s.route for s in document.screens}
    list_routes = _list_routes(document)
    files: dict[str, str] = {}
    files.update(_static_files(package_name(title), title, header))
    files["src/styles.css"] += brand_css(theme)
    files["src/app/forms.ts"] = header + "\n" + FORMS_TS
    files["src/app/data/store.ts"] = header + "\n" + STORE_TS
    files["src/app/data/entities.ts"] = entities_ts(spec, header)
    warnings = [i for i in issues if i.severity == "warning"]
    registered: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for index, screen in enumerate(document.screens):
        builder = ScreenBuilder(screen, index, spec, list_routes, routes)
        cls, source = builder.file(header)
        if cls in seen:
            raise GenerationError(f"two screens map to the class name {cls}")
        seen.add(cls)
        files[f"src/app/screens/{cls_file(cls)}.ts"] = source
        registered.append((cls, screen.route.lstrip("/"), screen.title))
        warnings += builder.warnings
    files["src/app/app.ts"] = _app_ts(header, title, [(p, t) for _, p, t in registered])
    files["src/app/app.routes.ts"] = _routes_ts(header, registered)
    files["README.md"] = _readme(title, spec_revision, contract, registered)
    project = GeneratedProject(
        generator=f"{GENERATOR}@{GENERATOR_VERSION}",
        spec_revision=spec_revision,
        design_system=design_system_label(contract, theme),
        files=dict(sorted(files.items())),
        warnings=warnings,
    )
    manifest = {
        "generator": project.generator,
        "spec_revision": spec_revision,
        "ui_ir_version": document.ir_version,
        "design_system": project.design_system,
        "library": f"{contract.library.package}@{contract.library.version}",
        "files": {path: project.sha256(path) for path in project.files},
    }
    project.files[MANIFEST] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    project.files = dict(sorted(project.files.items()))
    return project
