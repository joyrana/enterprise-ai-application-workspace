def test_dependencies_are_pinned_exactly_to_the_angular_toolchain_lockfile() -> None:
    folder = ROOT / "toolchains" / "angular"
    tools = toolchain()
    package = json.loads((folder / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((folder / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    for group in ("dependencies", "devDependencies"):
        assert package[group] == tools[group], group
        for name, version in tools[group].items():
            assert re.fullmatch(r"\d+\.\d+\.\d+", version), f"{name} must be pinned exactly"
            assert lock[f"node_modules/{name}"]["version"] == version, name
    assert tools["dependencies"]["@angular/material"] == CONTRACT.library.version


def test_hostile_spec_text_never_reaches_templates(raw: dict[str, Any]) -> None:
    evil = 'Pwn`${alert(1)}`</script><b>{{ constructor.constructor("x")() }}</b> \u2028 é'
    raw["metadata"]["name"] = evil
    raw["screens"][0]["name"] = evil
    raw["screens"][0]["components"][0]["label"] = evil
    raw["entities"][0]["name"] = evil
    project = generate_project(load_spec(raw), CONTRACT, spec_revision=2)
    for path, template in templates(project.files).items():
        assert "Pwn" not in template, path
        assert "{{ constructor" not in template, path
    for path, content in project.files.items():
        if path.endswith(".ts"):
            outside = content.replace(literal(evil), '""')
            assert "Pwn" not in outside, path
            assert "\u2028" not in content, path
            assert "`${" not in content.replace("`${Date.now()", "").replace("`generated-app:${", ""), path
    assert "&lt;/script&gt;" in project.files["src/index.html"]


def test_templates_use_only_allowlisted_markup_and_contract_components(raw: dict[str, Any]) -> None:
    spec = load_spec(entities_only(raw))
    document = derive_document(spec)
    routes = {s.id: s.route for s in document.screens}
    material_names = " ".join(c for m in CONTRACT.mappings.values() for c in m.components)
    for index, screen in enumerate(document.screens):
        builder = ScreenBuilder(screen, index, spec, _list_routes(document), routes)
        builder.file("// header\n")
        tags, attrs = builder.used()
        assert tags <= ELEMENTS
        assert attrs <= set(ATTRIBUTES)
        for tag in tags:
            if tag.startswith("mat-"):
                assert tag in material_names, tag
        for attr in attrs:
            if attr.startswith(("mat", "*mat")) and attr not in ("matColumnDef",):
                assert attr.lstrip("*") in material_names or attr.lstrip("*").startswith(
                    ("matHeader", "matCell", "matRow", "matNoDataRow")
                ), attr


def test_template_builder_refuses_anything_off_the_allowlist() -> None:
    with pytest.raises(GenerationError, match="element 'script'"):
        Element("script")
    with pytest.raises(GenerationError, match="attribute 'onclick'"):
        Element("button", [("onclick", "alert(1)")])
    with pytest.raises(GenerationError, match="unsafe expression"):
        Element("button", [("(click)", "go('x')")])
    with pytest.raises(GenerationError, match="not allowed for 'class'"):
        Element("div", [("class", "x onmouseover")])
    with pytest.raises(GenerationError, match="unsafe interpolation"):
        interpolate("t.k0 }}<script>")
    with pytest.raises(GenerationError, match="unsafe control-flow"):
        Element("div", [], ["<b>raw text</b>"])


