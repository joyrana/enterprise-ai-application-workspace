def test_ir_errors_block_generation_and_react_contracts_are_refused(raw: dict[str, Any]) -> None:
    spec = load_spec(raw)
    broken = derive_document(spec).model_copy(
        update={
            "screens": [
                Screen(
                    id="s",
                    title="S",
                    route="/s",
                    source=ScreenSource(kind="spec-screen", ref="s"),
                    body=[Heading(id="h", text="S", level=1), Form(id="f", label="F")],
                )
            ]
        }
    )
    with pytest.raises(GenerationBlocked):
        generate_project(spec, CONTRACT, document=broken)
    fluent = get_contract("fluent2")
    assert fluent is not None
    with pytest.raises(GenerationError, match="not an Angular design system"):
        generate_project(spec, fluent)
